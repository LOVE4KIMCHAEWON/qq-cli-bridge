export function formatHelpText(): string {
  return [
    "QQ CLI Bridge commands",
    "",
    "/help",
    "  Show this help.",
    "",
    "/model",
    "  Show backend, current model, and available models.",
    "",
    "/model <model-id>",
    "  Switch the model for this QQ conversation (subsequent turns).",
    "",
    "/model default",
    "  Restore the CLI default model for this conversation.",
    "",
    "/persona",
    "  Show Persona file path and reload hints (does not print Persona text).",
    "",
    "/memory",
    "  List compact long-term memories for this QQ conversation.",
    "",
    "/memory forget <id>",
    "  Delete (deactivate) a memory item by id.",
    "",
    "/memory clear",
    "  Clear all active memories for this conversation.",
    "",
    "/image <query>",
    "  Search images (DDGS → SearXNG → Duitang) and send to this chat.",
    "  Optional: /image --provider=ddgs <query>. NL「来张…」also works. No AI generation.",
    "",
    "Normal messages (without a leading /command) go to the active AI CLI.",
  ].join("\n");
}
